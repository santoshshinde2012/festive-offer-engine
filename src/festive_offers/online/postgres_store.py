def validate_schema_name(schema: str) -> str:
    """Require an isolated schema before opening a database or creating resources."""
    if (
        not isinstance(schema, str)
        or not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", schema)
        or schema.startswith("pg_")
        or schema in {"public", "information_schema"}
    ):
        raise ValueError("Use a dedicated lowercase PostgreSQL schema name")
    return schema


class PostgreSQLStore:
    """Provide atomic semantic repositories using a dedicated PostgreSQL schema.

    A connection factory may mint a fresh Lakebase credential per connection. It
    must return a new, idle psycopg 3 connection owned by this store. Every writer
    must use this store's lock protocol. Schema creation is an explicit option so
    deployment migrations can run separately from a restricted application role.
    """

    def __init__(
        self,
        dsn: str = "",
        *,
        schema: str = "festive_offers",
        connection_factory: Callable[[], Connection[Any]] | None = None,
        initialize: bool = True,
        connect_timeout_seconds: int = 10,
        lock_timeout_ms: int = 10_000,
        statement_timeout_ms: int = 30_000,
    ) -> None:
        validate_schema_name(schema)
        for name, value in (
            ("connect_timeout_seconds", connect_timeout_seconds),
            ("lock_timeout_ms", lock_timeout_ms),
            ("statement_timeout_ms", statement_timeout_ms),
        ):
            if type(value) is not int or value < 1:
                raise ValueError(f"{name} must be a positive integer")
        if not dsn and connection_factory is None:
            raise ValueError("Provide a PostgreSQL DSN or a fresh-connection factory")
        self.dsn = dsn
        self.schema = schema
        self.connection_factory = connection_factory
        self.connect_timeout_seconds = connect_timeout_seconds
        self.lock_timeout_ms = lock_timeout_ms
        self.statement_timeout_ms = statement_timeout_ms
        self._lock_key = int.from_bytes(
            hashlib.sha256(f"festive-offers:{schema}".encode()).digest()[:8], "big", signed=True
        )
        if initialize:
            self.initialize_schema()

    def connect(self) -> Connection[Record]:
        """Return an idle, store-owned connection without leaking credential data."""
        try:
            import psycopg
            from psycopg.pq import TransactionStatus
            from psycopg.rows import dict_row
        except ImportError as error:
            raise RuntimeError("PostgreSQL requires optional requirements-postgres.txt") from error
        connection = (
            self.connection_factory()
            if self.connection_factory is not None
            else psycopg.connect(
                self.dsn, connect_timeout=self.connect_timeout_seconds, row_factory=dict_row
            )
        )
        try:
            if connection.info.transaction_status != TransactionStatus.IDLE:
                raise ValueError("The connection factory must return a new idle connection")
            connection.autocommit = True
            connection.row_factory = dict_row
        except BaseException:
            connection.close()
            raise
        return cast("Connection[Record]", connection)

    @contextmanager
    def transaction(self) -> Iterator[Connection[Record]]:
        """Serialize before caller time/eligibility reads; roll back every failure."""
        connection = self.connect()
        from psycopg import sql

        try:
            connection.execute("BEGIN ISOLATION LEVEL READ COMMITTED")
            connection.execute(
                "SELECT pg_catalog.set_config('statement_timeout', %s, true)",
                (str(self.statement_timeout_ms),),
            )
            connection.execute(
                "SELECT pg_catalog.set_config('lock_timeout', %s, true)",
                (str(self.lock_timeout_ms),),
            )
            connection.execute("SELECT pg_catalog.pg_advisory_xact_lock(%s)", (self._lock_key,))
            connection.execute(
                sql.SQL("SET LOCAL search_path TO {}, pg_catalog").format(
                    sql.Identifier(self.schema)
                )
            )
            yield connection
            connection.commit()
        except BaseException:
            connection.rollback()
            raise
        finally:
            connection.close()

    def initialize_schema(self) -> None:
        """Create only this adapter's tables; leave existing campaign state intact."""
        with self.transaction() as connection:
            from psycopg import sql

            connection.execute(
                sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(self.schema))
            )
            for statement in SCHEMA.split(";"):
                if statement.strip():
                    connection.execute(statement)

    @contextmanager
    def unit_of_work(self) -> Iterator[UnitOfWork]:
        from .postgres_repository import PostgreSQLUnitOfWork

        with self.transaction() as connection:
            yield PostgreSQLUnitOfWork(connection)

    def rows(self, table: str) -> list[dict[str, Any]]:
        if table not in EXPORT_TABLES:
            raise ValueError("Unknown export table")
        with self.transaction() as connection:
            return connection.execute(
                f'SELECT * FROM "{table}"'
                + (" ORDER BY event_sequence" if table == "events" else "")
            ).fetchall()

    def export(self, destination: Path, reports: Mapping[str, Any]) -> ExportManifest:
        """Copy 13 tables under shared locks, then write the common evidence format.

        Reports retain their separately declared pre-export scope. Shared table
        locks also block direct writers bypassing the application advisory lock.
        Filesystem work begins after the database transaction and locks finish.
        """
        tables: dict[str, TableSnapshot] = {}
        with self.transaction() as connection:
            connection.execute("LOCK TABLE " + ",".join(EXPORT_TABLES) + " IN SHARE MODE")
            for table in EXPORT_TABLES:
                cursor = connection.execute(
                    f'SELECT * FROM "{table}"'
                    + (" ORDER BY event_sequence" if table == "events" else "")
                )
                assert cursor.description is not None
                tables[table] = TableSnapshot(
                    columns=tuple(column.name for column in cursor.description),
                    rows=tuple(cursor.fetchall()),
                )
        return write_operational_export(
            destination,
            tables,
            reports,
            scope="consistent PostgreSQL table snapshot protected by table locks; reports obtained before export",
        )
