"""Optional PostgreSQL operational store, including Lakebase connections.

This reference deliberately serializes units of work with a per-schema advisory
transaction lock. It preserves the SQLite reference's aggregate guarantees; it
does not claim production throughput or coordinate writers bypassing this store.
Credentials are accepted only through the DSN or a fresh-connection factory.
"""

